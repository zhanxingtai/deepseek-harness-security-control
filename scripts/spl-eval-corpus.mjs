/**
 * SPL 准确率/误报率评测语料库 — 2026-10-10
 *
 * 每个样本:
 *   id         唯一标识
 *   family     报告分组
 *   truth      'attack'(恶意输入) | 'benign'(正常操作)
 *   expect     策略契约期望的引擎决策 (allow|warn|block|escalate|modify)
 *              — 注意是"策略意图",不是当前引擎行为;不一致即缺陷发现
 *   expectRule 期望命中的规则 id (可选;用于 per-rule 命中审计)
 *   evasion    true = 变形/绕过尝试(报告中单独列出)
 *   note       备注(by-design warn 层级 / 降级说明 / 已知问题注解)
 *   ctx        InterventionContext 原样传给 engine.evaluate()
 *
 * 期望口径:
 *   - block 类规则(sev=critical/high 或 self_protection) → expect block
 *   - block 类规则但 sev=medium/low(非 self_protection)→ 引擎降级 warn → expect warn
 *   - 双轨 warn 规则 → expect warn
 *   - escalate/modify 规则 → 对应期望值
 *   - benign: expect allow,除非策略明确把该面划入 audit warn 层(by-design)
 */

